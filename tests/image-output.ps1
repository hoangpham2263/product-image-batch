. (Join-Path $PSScriptRoot 'helpers.ps1')
$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
. (Join-Path $root 'src/bootstrap.ps1')
$temp=Join-Path $TestWorkspaceRoot ('image-output-'+[Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $temp|Out-Null
try{
    $valid=Join-Path $temp 'valid.png';New-TestPng $valid 37 29 ([byte[]](255,0,255))
    $before=Get-BytesHash ([IO.File]::ReadAllBytes($valid))
    Assert-GeneratedImage $valid
    $large=Join-Path $temp 'large.png';New-TestPng $large 1024 32
    $size=Get-ImageSize ([IO.File]::ReadAllBytes($large))
    if($size.Width -ne 1024 -or $size.Height -ne 32){throw 'Byte shifts truncated image dimensions.'}
    Assert-GeneratedImage $large
    if((Get-BytesHash ([IO.File]::ReadAllBytes($valid))) -ne $before){throw 'Validation altered the generated image.'}
    $bad=Join-Path $temp 'bad.png';[IO.File]::WriteAllText($bad,'not an image')
    foreach($path in @($bad,(Join-Path $temp 'missing.png'))){
        $blocked=$false;try{Assert-GeneratedImage $path}catch{$blocked=$_.Exception.Message -like 'Image technical validation failed:*'}
        if(-not $blocked){throw 'Invalid/missing image was accepted.'}
    }
    Write-Host 'PASS: readable PNG validation preserves exact generated bytes; invalid/missing files are blocked.' -ForegroundColor Green
}finally{
    $resolved=[IO.Path]::GetFullPath($temp);$allowed=[IO.Path]::GetFullPath($TestWorkspaceRoot).TrimEnd('\')+'\'
    if($resolved.StartsWith($allowed,[StringComparison]::OrdinalIgnoreCase) -and (Split-Path $resolved -Leaf) -like 'image-output-*'){Remove-Item -LiteralPath $resolved -Recurse -Force}
}
